#!/usr/bin/env python3
"""Regenerate js/data/geo.js from dataref/geo_final.json.

    python3 dataref/build_geo.py

geo_final.json is the curated matcher output (see dataref/README.md).
Run this after editing geo_final.json — never edit geo.js by hand.
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
gf = json.loads((root / "dataref" / "geo_final.json").read_text())

lines = [
    "/* Real station coordinates & elevations - derived from the open Indian-Railway-Data",
    "   station dataset (OSM-derived coordinates, github.com/prasenjit-27/Indian-Railway-Data)",
    "   plus manual anchors for halts absent from it. km = haversine x winding factor.",
    "   GENERATED by dataref/build_geo.py - edit geo_final.json, not this file. */",
    "const GEO = {",
]
for rid in sorted(gf):
    r = gf[rid]
    sts = ", ".join(
        "{n:%s,lat:%s,lon:%s,km:%s,elev:%s}"
        % (json.dumps(s["n"]), s["lat"], s["lon"], s["km"], s["elev"])
        for s in r["stations"]
    )
    lines.append("  %s: { winding: %s, stations: [%s] }," % (json.dumps(rid), r.get("winding", 1.0), sts))
lines.append("};")

out = root / "js" / "data" / "geo.js"
out.write_text("\n".join(lines) + "\n")
print("wrote", out.relative_to(root), "with", sum(len(r["stations"]) for r in gf.values()), "stations")
